#!/usr/bin/env -S uv run
"""Import Moss **card transactions** (WSJ27 Custom-CSV) into two tables.

Source: the Moss CSV-Builder "WSJ27" export of the *Transaction* format (see
hitobito_wsjrdp_2027/doc/moss_data_model.md section 5.2). Semicolon-separated,
UTF-8, ISO dates (YYYY-MM-DD), decimal point ".".

Target (one CSV row = one split of a card transaction):
  * moss_card_transactions          -- one row per `Transaction ID`
    (= card_transaction_uuid); fields identical across splits.
  * moss_card_transaction_bookings  -- one row per split; fields that differ per
    split. References its transaction by the natural key `card_transaction_uuid`.

Column handling (see doc 5.2.7):
  * OTHER_COLUMNS_*  -- >70%-empty columns -> the target's `other_moss_columns` jsonb,
                        only when a value is present.
  * DERIVED_FROM_UUID -- Moss Record/Attachment URL + Transaction ID PDF filename:
                        NOT stored (derivable from the Transaction ID); stashed
                        into the transaction's other_moss_columns only if the CSV value
                        deviates from the derived one.
  * ALWAYS_MIRROR_* -- every amount/currency/rate column, mirrored verbatim into
                        `other_moss_columns` under its Moss name, even when a
                        house column holds the same value (source fidelity).
  * IGNORED / NOT_EXPORTED -- present in the CSV but never stored.

Money columns follow doc/money_conventions.md: Moss delivers SIGNED amounts, so
`signed_base_amount` (Home) / `signed_transaction_amount` (Original) are stored
as-is and the unsigned `base_amount` / `transaction_amount` plus `debit_credit`
are generated by the DB. `exchange_rate` and the Kontenart columns
(`account_kind` on the lines, `supplier_account_kind` /
`moss_balance_account_kind` / `cash_in_transit_account_kind` on the transaction)
are derived here; the matching `*_type` classes are generated by the DB.
`signed_total_base_amount` is the sum of a transaction's lines, cross-checked
against the Moss "Total Amount". Non-EUR Home Currency is refused.

`source_file` is provenance, not content: it is kept out of the diffed column
sets, so a renamed file alone never triggers an UPDATE -- it is written on INSERT
and refreshed only on rows that change anyway (same rule as the DTVF importer).

Manual / Hitobito-side columns (subject_id/subject_type, comment, status,
additional_info; the
DATEV links moss_card_transactions.clearing_datev_booking_id and the booking's
expense_datev_booking_id, each with their *_link_meta) are NEVER written and are
preserved on UPDATE (only Moss-mapped columns + other_moss_columns are refreshed).

Import logic, keyed on `Transaction ID` (= card_transaction_uuid):
  1. No DB transaction     -> INSERT the transaction + all its booking rows.
  2. TX exists, exactly one CSV booking AND one DB booking
                           -> diff + UPDATE that booking (and the TX row).
  3. TX exists, bookings match 1:1 on `Unique Item Number`
                           -> diff + UPDATE each matched booking (and the TX row).
  4. TX exists, different booking counts / differing Unique Item Numbers
                           -> ERROR (abort before any write).

Idempotent: re-importing the same file changes nothing (verified).
Safety: writes go through ctx.require_approval_to_run_in_prod(); honors ctx.dry_run.
"""

