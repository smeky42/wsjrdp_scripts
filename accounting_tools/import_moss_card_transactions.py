def _as_text(value) -> str:
    if value is None:
        return ""
    if isinstance(value, _decimal.Decimal):
        return format(value.normalize(), "f")
    if isinstance(value, _dt.date):
        return value.isoformat()
    return str(value)


def _changed(new_rec: dict, db_row: dict, columns) -> dict:
    """Mapped columns (+ other_moss_columns) whose new value differs from the stored one."""
    changed = {}
    for col in columns:
        if _as_text(new_rec.get(col)) != _as_text(db_row.get(col)):
            changed[col] = new_rec.get(col)
    if (new_rec.get("other_moss_columns") or {}) != (
        db_row.get("other_moss_columns") or {}
    ):
        changed["other_moss_columns"] = new_rec.get("other_moss_columns") or {}
    return changed


# --- DB access ----------------------------------------------------------------


def _fetch_rows(cur, table: str, columns: list[str], where: str, param) -> list[dict]:
    cur.execute(f"SELECT {', '.join(columns)} FROM {table} WHERE {where}", (param,))
    names = [d.name for d in cur.description]
    return [dict(zip(names, values)) for values in cur.fetchall()]


def _fetch_tx(cur, uuids: list[str]) -> dict[str, dict]:
    if not uuids:
        return {}
    columns = [*TX_COLUMN_MAP.values(), *_TX_DERIVED, "id", "other_moss_columns"]
    rows = _fetch_rows(cur, TX_TABLE, columns, f"{_UUID} = ANY(%s)", uuids)
    return {r[_UUID]: r for r in rows}


def _fetch_bookings(cur, uuids: list[str]) -> dict[str, list[dict]]:
    if not uuids:
        return {}
    columns = [
        *BOOKING_COLUMN_MAP.values(),
        *_BOOKING_DERIVED,
        "id",
        _UUID,
        "other_moss_columns",
    ]
    rows = _fetch_rows(cur, BOOKING_TABLE, columns, f"{_UUID} = ANY(%s)", uuids)
    by_uuid: dict[str, list[dict]] = {}
    for r in rows:
        by_uuid.setdefault(r[_UUID], []).append(r)
    return by_uuid


def _insert_tx(cur, tx_rec: dict) -> None:
    placeholders = ", ".join(["%s"] * len(_TX_WRITE))
    params = [
        Jsonb(tx_rec[c]) if c == "other_moss_columns" else tx_rec[c] for c in _TX_WRITE
    ]
    cur.execute(
        f"INSERT INTO {TX_TABLE} ({', '.join(_TX_WRITE)}) VALUES ({placeholders})",
        params,
    )


def _insert_bookings(cur, bookings: list[dict]) -> None:
    placeholders = ", ".join(["%s"] * len(_BOOKING_WRITE))
    sql = f"INSERT INTO {BOOKING_TABLE} ({', '.join(_BOOKING_WRITE)}) VALUES ({placeholders})"
    params = [
        [Jsonb(b[c]) if c == "other_moss_columns" else b[c] for c in _BOOKING_WRITE]
        for b in bookings
    ]
    cur.executemany(sql, params)


def _update_row(cur, table: str, db_id: int, changed: dict) -> None:
    set_sql = ", ".join(f"{c} = %s" for c in changed)
    params = [Jsonb(v) if c == "other_moss_columns" else v for c, v in changed.items()]
    cur.execute(
        f"UPDATE {table} SET {set_sql}, updated_at = NOW() WHERE id = %s",
        [*params, db_id],
    )


# --- import -------------------------------------------------------------------


def _import(cur, grouped: dict, *, dry_run: bool) -> None:
    existing_tx = _fetch_tx(cur, list(grouped))
    existing_bookings = _fetch_bookings(cur, list(existing_tx))

    errors: list[str] = []
    n_tx_ins = n_tx_upd = n_bk_ins = n_bk_upd = 0

    for uuid, (tx_rec, booking_recs) in grouped.items():
        if uuid not in existing_tx:  # case 1: new transaction
            n_tx_ins += 1
            n_bk_ins += len(booking_recs)
            if not dry_run:
                _insert_tx(cur, tx_rec)
                _insert_bookings(cur, booking_recs)
            continue

        db_tx = existing_tx[uuid]
        tx_changed = _changed(tx_rec, db_tx, _TX_DIFF)
        if tx_changed:
            tx_changed["source_file"] = tx_rec["source_file"]
            n_tx_upd += 1
            if not dry_run:
                _update_row(cur, TX_TABLE, db_tx["id"], tx_changed)

        matched = _match_bookings(
            uuid, booking_recs, existing_bookings.get(uuid, []), errors
        )
        if matched is None:
            continue
        for booking_rec, db_booking in matched:
            bk_changed = _changed(booking_rec, db_booking, _BOOKING_DIFF)
            if bk_changed:
                bk_changed["source_file"] = booking_rec["source_file"]
                n_bk_upd += 1
                if not dry_run:
                    _update_row(cur, BOOKING_TABLE, db_booking["id"], bk_changed)

    if errors:
        for msg in errors:
            _LOGGER.error("%s", msg)
        raise SystemExit(
            f"Abbruch: {len(errors)} Transaktion(en) ohne klares Buchungs-Match."
        )

    _LOGGER.info(
        "Transaktionen: %d | TX INSERT/UPDATE: %d/%d | Buchungen INSERT/UPDATE: %d/%d",
        len(grouped),
        n_tx_ins,
        n_tx_upd,
        n_bk_ins,
        n_bk_upd,
    )


def _match_bookings(uuid, booking_recs, db_bookings, errors):
    """Return [(csv_booking, db_booking), ...] or None (recording a case-4 error)."""
    if len(booking_recs) == 1 and len(db_bookings) == 1:  # case 2
        return [(booking_recs[0], db_bookings[0])]
    csv_by_uin = {b[_UIN]: b for b in booking_recs}
    db_by_uin = {b[_UIN]: b for b in db_bookings}
    clean = (
        len(csv_by_uin) == len(booking_recs)
        and len(db_by_uin) == len(db_bookings)
        and set(csv_by_uin) == set(db_by_uin)
    )
    if not clean:  # case 4
        errors.append(
            f"Transaction ID {uuid}: Buchungen CSV={len(booking_recs)} DB={len(db_bookings)}; "
            f"Unique Item Numbers CSV={sorted(csv_by_uin)} DB={sorted(db_by_uin)}"
        )
        return None
    return [(csv_by_uin[uin], db_by_uin[uin]) for uin in csv_by_uin]  # case 3


def create_argument_parser():
    import argparse

    p = argparse.ArgumentParser(description="Import Moss WSJ27 card transactions")
    p.add_argument("csv_files", nargs="+", help="Moss WSJ27 card-transaction CSV(s)")
    return p


def main(argv=None):
    ctx = wsjrdp2027.WsjRdpContext(argument_parser=create_argument_parser(), argv=argv)
    out_base = ctx.make_out_path(_SELF_NAME)
    ctx.configure_log_file(out_base.with_suffix(".log"))

    grouped = _read_grouped(ctx.parsed_args.csv_files)

    with ctx.psycopg_connect() as conn:
        if not ctx.dry_run:
            ctx.require_approval_to_run_in_prod()
        with conn.cursor() as cur:
            _import(cur, grouped, dry_run=ctx.dry_run)
        if ctx.dry_run:
            _LOGGER.info("[dry-run] Keine Änderungen geschrieben.")
            conn.rollback()
        else:
            conn.commit()

    _LOGGER.info("Output directory: %s", ctx.out_dir)


if __name__ == "__main__":
    _sys.exit(main())
