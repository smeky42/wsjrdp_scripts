def _derived_url_values(transaction_id: str) -> dict[str, str]:
    record = f"{_MOSS_RECORD_URL_PREFIX}{transaction_id}"
    return {
        "moss_record_url": record,
        "moss_attachment_url": record.removeprefix("https://"),
        "transaction_id_pdf_filename": f"{transaction_id}.pdf",
    }


def _coerce(db_col: str, raw: str):
    value = (raw or "").strip()
    if value == "":
        return "" if db_col in _NOT_NULL_STR_COLS else None
    if db_col in _DATE_COLS:
        return _dt.date.fromisoformat(value)
    if db_col in _DECIMAL_COLS:
        return _decimal.Decimal(value.replace(",", "."))
    if db_col in _INT_COLS:
        return int(value)
    return value


def _mapped(csv_row: dict[str, str], column_map: dict[str, str]) -> dict[str, object]:
    return {
        db: _coerce(db, csv_row.get(header, "")) for header, db in column_map.items()
    }


def _account_kind(number: object) -> str:
    """Kontenart of an account number taken from a _mapped() record. Those
    records are typed `object` (they mix str/None/date/Decimal/int, see
    _coerce); the account-number columns are never coerced, so they are always
    str or None."""
    return wsjrdp2027.datev.account_kind_for_account_number(
        number if isinstance(number, str) else None
    )


def _other(csv_row: dict[str, str], other_map: dict[str, str]) -> dict[str, object]:
    result: dict[str, object] = {}
    for header, key in other_map.items():
        val = (csv_row.get(header) or "").strip()
        if val:
            result[key] = val
    return result


def _mirror(csv_row: dict[str, str], headers: tuple[str, ...]) -> dict[str, object]:
    """Verbatim mirror of the money/currency columns (see ALWAYS_MIRROR_*).

    Keyed by the Moss field-reference name, value the raw CSV string; empty
    cells are kept as "".  Columns missing from the file are skipped."""
    return {h: (csv_row.get(h) or "").strip() for h in headers if h in csv_row}


def _exchange_rate(base, transaction, base_currency, transaction_currency):
    """transaction = base * exchange_rate, derived as |transaction| / |base|.

    Quantity notation (Mengennotierung): transaction-currency units per one unit
    of the base currency, e.g. EUR->PLN ~ 4.24. Same direction DATEV delivers in
    its Kurs field, so the rates of both tables are comparable (see
    doc/fin/money_conventions.md R4).

    Equal amounts mean a rate of exactly 1 -- that is the normal case here (both
    figures in EUR), and storing 1 instead of NULL keeps `base * exchange_rate`
    usable without a NULL check. NULL is left for the cases where no rate can be
    derived: a missing amount, a zero base, or the contradictory combination of
    one currency with two different amounts.

    Moss's own Conversion Rate is unreliable (observed constant 1.0/NULL even on
    genuine FX rows), so it is never used here; it is kept verbatim in
    other_moss_columns."""
    if base is None or transaction is None:
        return None
    if base == transaction:
        return _decimal.Decimal(1)
    if base_currency == transaction_currency or not base:
        return None
    return abs(transaction) / abs(base)


def _row_to_records(csv_row: dict[str, str]) -> tuple[dict, dict]:
    """One CSV row -> (transaction record, booking record)."""
    tx = _mapped(csv_row, TX_COLUMN_MAP)
    tx_other = _other(csv_row, OTHER_COLUMNS_TX) | _mirror(csv_row, ALWAYS_MIRROR_TX)
    transaction_id = (csv_row.get(KEY_CSV) or "").strip()
    derived = _derived_url_values(transaction_id)
    for header, key in DERIVED_FROM_UUID.items():
        val = (csv_row.get(header) or "").strip()
        if val and val != derived[key]:
            tx_other[key] = val
    for number_col, kind_col in _TX_ACCOUNT_KINDS.items():
        tx[kind_col] = _account_kind(tx[number_col])
    tx["other_moss_columns"] = tx_other

    # The card_transaction_uuid columns are of type uuid: keep the key typed
    # (a str would neither match the fetched rows nor bind against uuid[]).
    # The URL derivation above deliberately uses the verbatim CSV spelling.
    try:
        transaction_uuid = _uuid.UUID(transaction_id)
    except ValueError:
        raise ValueError(
            f"CSV row with malformed Transaction ID {transaction_id!r} "
            "(expected a UUID)"
        ) from None
    tx[_UUID] = transaction_uuid

    booking = _mapped(csv_row, BOOKING_COLUMN_MAP)
    booking[_UUID] = transaction_uuid  # natural-key FK to the transaction
    booking["other_moss_columns"] = _other(csv_row, OTHER_COLUMNS_BOOKING) | _mirror(
        csv_row, ALWAYS_MIRROR_BOOKING
    )
    # Accounting is kept in EUR; refuse anything else rather than silently
    # storing a non-EUR "base" amount (the DB check constraint would fail too).
    if booking["base_currency"] != "EUR":
        raise SystemExit(
            f"Transaction {transaction_id}: Home Currency is "
            f"{booking['base_currency']!r}, expected EUR -- refusing the import."
        )
    booking["account_kind"] = _account_kind(booking["account_number"])
    booking["exchange_rate"] = _exchange_rate(
        booking["signed_base_amount"],
        booking["signed_transaction_amount"],
        booking["base_currency"],
        booking["transaction_currency"],
    )
    return tx, booking


def _validate_headers(headers: list[str], csv_filename: str) -> None:
    known = (
        set(TX_COLUMN_MAP)
        | set(BOOKING_COLUMN_MAP)
        | set(OTHER_COLUMNS_TX)
        | set(OTHER_COLUMNS_BOOKING)
        | set(DERIVED_FROM_UUID)
        | set(ALWAYS_MIRROR_TX)
        | set(ALWAYS_MIRROR_BOOKING)
        | IGNORED
        | NOT_EXPORTED
    )
    unknown = [h for h in headers if h not in known]
    if unknown:
        raise SystemExit(
            f"{csv_filename}: unbekannte CSV-Spalten (bitte klassifizieren): {unknown}"
        )


def _read_grouped(csv_filenames: list[str]):
    """Return {uuid: (tx_record, [booking_record, ...])}, grouped over all files."""
    tx_by_uuid: dict[str, dict] = {}
    bookings_by_uuid: dict[str, list[dict]] = {}
    for csv_filename in csv_filenames:
        _LOGGER.info("Moss card-transaction CSV: %s", csv_filename)
        with open(csv_filename, newline="", encoding="utf-8-sig") as fh:
            reader = _csv.DictReader(fh, delimiter=CSV_DELIMITER)
            _validate_headers(list(reader.fieldnames or []), csv_filename)
            source_file = _pathlib.Path(csv_filename).name
            for csv_row in reader:
                tx, booking = _row_to_records(csv_row)
                tx["source_file"] = booking["source_file"] = source_file
                uuid = tx[_UUID]
                if uuid in tx_by_uuid and _changed(
                    tx, tx_by_uuid[uuid], TX_COLUMN_MAP.values()
                ):
                    _LOGGER.warning(
                        "Transaction ID %s: uneinheitliche Transaktions-Felder über Splits",
                        uuid,
                    )
                tx_by_uuid.setdefault(uuid, tx)
                bookings_by_uuid.setdefault(uuid, []).append(booking)

    grouped = {}
    for uuid, tx in tx_by_uuid.items():
        bookings = bookings_by_uuid[uuid]
        tx["signed_total_base_amount"] = sum(b["signed_base_amount"] for b in bookings)
        _verify_total(uuid, tx, bookings)
        grouped[uuid] = (tx, bookings)
    return grouped


def _verify_total(uuid, tx: dict, bookings: list[dict]) -> None:
    """Cross-check the computed total against the Moss "Total Amount" mirror.

    Only comparable when the transaction is booked in our base currency (the
    Moss total is in the booking currency, our total in the base currency)."""
    mirror = tx["other_moss_columns"]
    if mirror.get("Currency") != mirror.get("Home Currency"):
        return
    raw = (mirror.get(_CSV_TOTAL_AMOUNT) or "").strip()
    if not raw:
        return
    moss_total = _decimal.Decimal(raw.replace(",", "."))
    computed = tx["signed_total_base_amount"]
    if moss_total != computed:
        raise SystemExit(
            f"Transaction {uuid}: Moss {_CSV_TOTAL_AMOUNT} ({moss_total}) does not "
            f"match the sum of its {len(bookings)} booking line(s) ({computed})."
        )


